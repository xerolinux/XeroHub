CREATE TABLE counts (edition TEXT NOT NULL, file TEXT NOT NULL, n INTEGER NOT NULL DEFAULT 0, PRIMARY KEY (edition, file));
CREATE TABLE links (user TEXT PRIMARY KEY, n INTEGER NOT NULL);
CREATE TABLE catalog (edition TEXT PRIMARY KEY, entry TEXT NOT NULL);
CREATE TABLE replaced (edition TEXT PRIMARY KEY, new_key TEXT NOT NULL, old_key TEXT);
CREATE TABLE catalog_backups (id INTEGER PRIMARY KEY AUTOINCREMENT, edition TEXT NOT NULL, entry TEXT, at INTEGER NOT NULL);
CREATE TABLE staff_attempts (user TEXT PRIMARY KEY, n INTEGER NOT NULL, t INTEGER NOT NULL);
